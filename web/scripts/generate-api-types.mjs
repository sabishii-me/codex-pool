import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "../..");
const schemaPath = resolve(root, "schemas/provider-connections-v2.schema.json");
const outputPath = resolve(root, "web/src/generated/provider-connections-v2.ts");
const schema = JSON.parse(readFileSync(schemaPath, "utf8"));

function typeOf(node) {
  if (node.$ref) return node.$ref.split("/").at(-1);
  if (node.type === "string") return "string";
  if (node.type === "number" || node.type === "integer") return "number";
  if (node.type === "boolean") return "boolean";
  if (node.type === "array") return `${typeOf(node.items)}[]`;
  if (node.type === "object") {
    if (node.properties) return objectBody(node);
    if (typeof node.additionalProperties === "object") return `Record<string, ${typeOf(node.additionalProperties)}>`;
    return "Record<string, unknown>";
  }
  return "unknown";
}

function objectBody(node) {
  const required = new Set(node.required ?? []);
  const fields = Object.entries(node.properties ?? {}).map(([name, property]) =>
    `  ${name}${required.has(name) ? "" : "?"}: ${typeOf(property)};`
  );
  return `{\n${fields.join("\n")}\n}`;
}

const definitions = Object.entries(schema.$defs ?? {}).map(([name, definition]) =>
  `export interface ${name} ${objectBody(definition)}`
);
const banner = `// Generated by scripts/generate-api-types.mjs from\n// schemas/provider-connections-v2.schema.json. Do not edit manually.\n\n`;
mkdirSync(dirname(outputPath), { recursive: true });
writeFileSync(outputPath, `${banner}${definitions.join("\n\n")}\n`);
